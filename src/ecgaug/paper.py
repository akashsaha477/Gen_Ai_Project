"""Phase 6: the paper's tables and numbers, generated from the result files (PLAN Phase 6, /paper).

    python -m ecgaug.paper      # writes paper/generated/*.tex, paper/generated/numbers.tex and paper/claims_vs_evidence.md

Every table cell and every number macro is computed here from a result file, and each table lists the
files it came from; nothing is typed by hand (docs/RULES.md rule 5). A result that does not exist yet is
written as ``\\missing{...}``, so ``paper/main.tex`` compiles at every stage of the project. Test numbers
appear only after the final evaluation (its own generated files are included as they are).
"""

from __future__ import annotations

import argparse
import csv
import json
import shutil
from pathlib import Path

from ecgaug import paths, workflow
from ecgaug.data.records import CLASSES
from ecgaug.names import (
    FINAL_EVAL,
    PHASE1_DATA,
    PHASE1_GATE,
    PHASE1_INPUT_REPRESENTATION,
    PHASE2_BASELINE_CLASSIFIERS,
    PHASE2_QUALITY_METRICS,
    PHASE3_CVAE,
    PHASE3_WGAN_GP,
    PHASE4_AUGMENTATION_POLICY,
    PHASE4_LEAKAGE_AUDIT,
    PHASE4_QUALITY_VS_GAIN,
    PHASE5_CLINICAL_NOTES,
    PHASE5_EXPLAINABILITY,
)


def _todo(text: str) -> str:
    """A visible placeholder for a result that does not exist yet (``\\missing`` is defined in paper/main.tex)."""
    return f"\\missing{{{_esc(text)}}}"


def _f(value, digits: int = 3) -> str:
    try:
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return "--"


def _table(columns: str, header: list[str], rows: list[list[str]], sources: list[str]) -> str:
    lines = [f"% Generated by python -m ecgaug.paper from: {', '.join(sources) or 'nothing yet'}", f"\\begin{{tabular}}{{{columns}}}", "\\toprule",
             " & ".join(header) + " \\\\", "\\midrule", *[" & ".join(r) + " \\\\" for r in rows], "\\bottomrule", "\\end{tabular}"]  # fmt: skip
    return "\n".join(lines) + "\n"


def _results(experiment: str) -> dict[str, dict]:
    return {k: v for k, v in workflow.experiment_results(experiment).items() if v}


def _esc(text: str) -> str:
    return str(text).replace("_", "\\_").replace("%", "\\%")


def dataset_table() -> tuple[str, dict]:
    """Table 1: records and class counts per split (DS2 counts are labels only, counted under a logged construction access)."""
    path = paths.results_for(PHASE1_DATA) / "record_counts.csv"
    if not path.is_file():
        return _table("l", ["Dataset"], [[_todo("record counts")]], []), {}
    from ecgaug.data.records import DS2
    from ecgaug.data.splits import load_approved_split

    with path.open(newline="") as fh:
        rows = list(csv.DictReader(fh))
    split = load_approved_split()
    parts = {"training": split.train, "validation": split.val, "test (DS2)": DS2}
    body, numbers = [], {}
    for name, records in parts.items():
        chosen = [r for r in rows if int(r["record"]) in records]
        counts = {c: sum(int(r[c]) for r in chosen) for c in CLASSES}
        body.append([name, str(len(records)), *[f"{counts[c]:,}" for c in CLASSES]])
        for c in CLASSES:
            numbers[f"count {name.split()[0]} {c}"] = counts[c]
    return _table("lrrrrr", ["Split", "Records", *CLASSES], body, [str(path.relative_to(paths.repo_root()))]), numbers


def classifier_table(experiment: str, label: str) -> tuple[str, dict]:
    """Variant tables of the classifier experiments (phase 1 representations, phase 2 baselines)."""
    results = _results(experiment)
    if not results:
        return _table("l", [label], [[_todo(f"{experiment} results")]], []), {}
    configs = workflow.experiment_configs(experiment)
    rows, numbers = [], {}
    for letter, r in results.items():
        seeds = r["per_seed"]
        f1 = {c: sum(s["f1"][c] for s in seeds) / len(seeds) for c in "SVF"}
        n_recall = sum(s["n_recall"] for s in seeds) / len(seeds)
        name = configs[letter].stem.split("_", 1)[1].replace("_", " ") if letter in configs else ""
        mark = "$^\\dagger$" if r.get("provisional") else ""
        rows.append([letter + mark, _esc(name), f"{_f(r['mean'])} $\\pm$ {_f(r['sd'])}", _f(f1["V"]), _f(f1["F"]), _f(n_recall)])
        numbers[f"{experiment} {letter} mean"] = r["mean"]
    return _table("llrrrr", ["Variant", "Name", "S F1 (val.)", "V F1", "F F1", "N recall"], rows,
                  [f"results/{experiment}/{l}.json" for l in results]), numbers  # fmt: skip


def quality_table() -> tuple[str, dict]:
    results = _results(PHASE2_QUALITY_METRICS)
    if not results:
        return _table("l", ["Metric"], [[_todo("phase2_quality_metrics results")]], []), {}
    rows = [[letter, _esc(r["family"]), "yes" if r["passed"] else "no", "yes" if r["reference_best"] else "no",
             ", ".join(_f(v, 2) for v in r["spearman"].values()), _f(r["median_cv"])] for letter, r in results.items()]  # fmt: skip
    return _table("llllll", ["Variant", "Family", "Passes", "Real best", "Spearman per degradation", "Median CV"], rows,
                  [f"results/{PHASE2_QUALITY_METRICS}/{l}.json" for l in results]), {}  # fmt: skip


def generator_table() -> tuple[str, dict]:
    """Table 3: pilot score, hard gates and diagnostics of every generator variant."""
    rows, sources = [], []
    for experiment in (PHASE3_CVAE, PHASE3_WGAN_GP):
        for letter, r in _results(experiment).items():
            low, high, c2st = workflow._diagnostic_extremes(r)
            rows.append([_esc(experiment.split("_", 1)[1]), letter, _esc(r["chosen_setting"]), f"{_f(r['mean'])} $\\pm$ {_f(r['sd'])}",
                         _f(low), _f(high), _f(c2st), "pass" if r["hard_gates"]["passed"] else "fail"])  # fmt: skip
            sources.append(f"results/{experiment}/{letter}.json")
    if not rows:
        rows = [[_todo("phase 3 pilot results")] + [""] * 7]
    return _table("llllrrrl", ["Family", "Variant", "Setting", "Pilot S F1", "Diversity (min)", "Memorization (max)", "C2ST (max)", "Hard gates"], rows, sources), {}


def policy_table() -> tuple[str, dict]:
    results = _results(PHASE4_AUGMENTATION_POLICY)
    if not results:
        return _table("l", ["Policy"], [[_todo("phase4_augmentation_policy results")]], []), {}
    rows = [[letter, _esc(r["policy"]["kind"]), str(r["pilot_strength"]), _f(r["mean"]), f"{r['constraint']['n_recall_drop']:+.3f}",
             "yes" if r["constraint"]["passed"] else "no"] for letter, r in results.items()]  # fmt: skip
    return _table("llrrrl", ["Variant", "Policy", "Pilot strength", "S F1 (val., 2 banks)", "$\\Delta$ N recall", "Within limit"], rows,
                  [f"results/{PHASE4_AUGMENTATION_POLICY}/{l}.json" for l in results]), {}  # fmt: skip


def quality_vs_gain_table() -> tuple[str, dict]:
    path = paths.results_for(PHASE4_QUALITY_VS_GAIN) / "summary.json"
    if not path.is_file():
        return _table("l", ["Metric"], [[_todo("RQ3: python -m ecgaug.eval.rq3")]], []), {}
    s = json.loads(path.read_text())
    rows = []
    for name, m in s["metrics"].items():
        ci = f"[{_f(m['ci_low'], 2)}, {_f(m['ci_high'], 2)}]" if m["ci_low"] is not None else "--"
        label = name.removeprefix("quality_").removesuffix("_mean")
        rows.append([_esc(label), _esc(m["group"]), _f(m["rho"], 2), ci, str(m["n_points"]), str(m["n_runs"])])
    note = " (provisional)" if s["provisional"] else ""
    return _table("llrrrr", ["Metric", "Group", "Spearman $\\rho$", "95\\% CI (runs resampled)", "Checkpoints", "Runs" + note], rows,
                  [f"results/{PHASE4_QUALITY_VS_GAIN}/summary.json"]), {}  # fmt: skip


def leakage_audit_table() -> tuple[str, dict]:
    path = paths.results_for(PHASE4_LEAKAGE_AUDIT) / "summary.json"
    if not path.is_file():
        return _table("l", ["Condition"], [[_todo("leakage audit (optional, after the final evaluation)")]], []), {}
    s = json.loads(path.read_text())

    def ci(e: dict | None) -> str:
        return f"{_f(e['point'])} [{_f(e['ci_low'])}, {_f(e['ci_high'])}]" if e else "--"

    rows = []
    for condition, c in s["conditions"].items():
        intra = f"{_f(c['intra']['mean'])} $\\pm$ {_f(c['intra']['sd'])}" if c["intra"] else "--"
        gain = s["gains"].get(condition)
        gain_intra = f"{float(gain['intra']['mean']):+.3f}" if gain and gain["intra"] else "--"
        rows.append([_esc(condition), intra, ci(c["inter"]), gain_intra, ci(gain["inter"]) if gain else "--"])
    header = ["Condition", "Intra-patient (mean $\\pm$ SD)", "Inter-patient [95\\% CI]", "Gain, intra", "Gain, inter [95\\% CI]"]
    return _table("lrrrr", header, rows, [f"results/{PHASE4_LEAKAGE_AUDIT}/summary.json", f"results/{FINAL_EVAL}/summary.json"]), {}


def explainability_table() -> tuple[str, dict]:
    results = _results(PHASE5_EXPLAINABILITY)
    if not results:
        return _table("l", ["Method"], [[_todo("phase5_explainability results")]], []), {}
    archs = sorted({a for r in results.values() for a in r["per_architecture"]})
    rows = []
    for letter, r in results.items():
        cells = []
        for arch in archs:
            e = r["per_architecture"].get(arch, {})
            cells += [_f(e.get("mean_gain"), 4), _f(e.get("mean_stability"))] if e.get("applicable") else ["n/a", "n/a"]
        rows.append([letter, _esc(r["method"]), *cells])
    header = ["Variant", "Method", *[h for a in archs for h in (f"{a} faithfulness gain", f"{a} stability")]]
    return _table("ll" + "rr" * len(archs), header, rows, [f"results/{PHASE5_EXPLAINABILITY}/{l}.json" for l in results]), {}


def notes_table() -> tuple[str, dict]:
    results = _results(PHASE5_CLINICAL_NOTES)
    if not results:
        return _table("l", ["Notes"], [[_todo("phase5_clinical_notes results")]], []), {}
    rows = []
    for letter, r in results.items():
        if r.get("not_run"):
            rows.append([letter, "not run", "", "", ""])
        else:
            rows.append([letter, str(r["unsupported_claims"]), _f(r["coverage"], 2), str(r["fell_back_to_template"]), _f(r["latency_s_mean"], 2)])
    return _table("lrrrr", ["Variant", "Unsupported claims", "Coverage", "Fell back", "Latency (s)"], rows,
                  [f"results/{PHASE5_CLINICAL_NOTES}/{l}.json" for l in results]), {}  # fmt: skip


def _macro(name: str) -> str:
    words = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}
    text = "".join(part.title() for part in name.replace("_", " ").replace("(", " ").replace(")", " ").split())
    return "".join(words.get(ch, ch) for ch in text if ch.isalnum())


def build() -> dict:
    """Write every generated file; return what was written and which inputs were still missing."""
    out = paths.repo_root() / "paper" / "generated"
    out.mkdir(parents=True, exist_ok=True)
    numbers: dict = {}
    written, missing = [], []
    for name, (tex, nums) in {
        "table_dataset": dataset_table(),
        "table_input_representation": classifier_table(PHASE1_INPUT_REPRESENTATION, "Representation"),
        "table_baselines": classifier_table(PHASE2_BASELINE_CLASSIFIERS, "Architecture"),
        "table_quality_metrics": quality_table(),
        "table_generators": generator_table(),
        "table_policy": policy_table(),
        "table_quality_vs_gain": quality_vs_gain_table(),
        "table_leakage_audit": leakage_audit_table(),
        "table_explainability": explainability_table(),
        "table_notes": notes_table(),
    }.items():  # fmt: skip
        (out / f"{name}.tex").write_text(tex)
        written.append(f"paper/generated/{name}.tex")
        if "\\missing" in tex:
            missing.append(name)
        numbers.update(nums)
    winner = workflow.phase1_winner() or (json.loads((paths.results_for(PHASE1_GATE) / "report.json").read_text())["winner"]
                                          if (paths.results_for(PHASE1_GATE) / "report.json").is_file() else None)  # fmt: skip
    lines = ["% Generated by python -m ecgaug.paper; do not edit. Every value comes from a result file."]
    lines += [f"\\newcommand{{\\{_macro(k)}}}{{{v:,}}}" if isinstance(v, int) else f"\\newcommand{{\\{_macro(k)}}}{{{_f(v)}}}" for k, v in sorted(numbers.items())]
    lines.append(f"\\newcommand{{\\PhaseOneWinner}}{{{winner or _todo('phase 1 winner')}}}")
    for tex in ("final_eval_conditions.tex", "final_eval_comparisons.tex"):  # written by the final evaluation, copied as they are
        source = paths.repo_root() / "tables" / tex
        if source.is_file():
            shutil.copy2(source, out / tex)
            written.append(f"paper/generated/{tex}")
        else:
            (out / tex).write_text(_todo("test results: written by /final-eval") + "\n")
            missing.append(tex)
    final_numbers = out / "numbers_final_eval.tex"
    if final_numbers.is_file():
        lines.append("\\input{generated/numbers_final_eval.tex}")
    (out / "numbers.tex").write_text("\n".join(lines) + "\n")
    written.append("paper/generated/numbers.tex")
    claims = paths.repo_root() / "paper" / "claims_vs_evidence.md"
    claims.write_text(
        "# Claims versus evidence\n\nGenerated by `python -m ecgaug.paper`. Each table of the draft, the result files it is built from, and their run IDs.\n\n"
        + "\n".join(f"- `{w}`" for w in written)
        + "\n\nTables still waiting for results: " + (", ".join(missing) if missing else "none") + "\n\n"
        "Add each claim of the paper below with the table or figure that supports it, before submission:\n\n| claim | evidence (table / figure) | run IDs |\n|---|---|---|\n"
    )  # fmt: skip
    return {"written": written, "missing": missing, "final_evaluation": (paths.results_for(FINAL_EVAL) / "summary.json").is_file()}


def main(argv: list[str] | None = None) -> int:
    argparse.ArgumentParser(description="Generate the paper's tables and numbers from the result files.").parse_args(argv)
    report = build()
    print(f"written {len(report['written'])} files under paper/generated/; still waiting for: {', '.join(report['missing']) or 'nothing'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
